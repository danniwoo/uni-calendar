import assert from "node:assert/strict";
import {attentionFixture} from "./fixtures/canvas-attention";
import {prepareCanvasImport,canvasAttemptTargets} from "../lib/canvas-prepare";
import {planCanvasImport,readCanvasBundle,type CanvasChoice} from "../lib/canvas-import";
import {preparedCanvasView} from "../lib/canvas-prepared-view";
import {canvasResultsHeadline,canvasUpdateStatus,canvasCheckFreshness} from "../lib/canvas-update-status";
import {canvasSourceRules,canvasSourceRuleReview} from "../lib/canvas-source-rules";
import {backupText,readBackup} from "../lib/backup";
const {board,bundle,old,raw}=attentionFixture(),before=JSON.stringify(board);
const prepared=prepareCanvasImport(board,bundle),choices=Object.values(prepared.choices),plan=planCanvasImport(board,bundle,choices);
const view=preparedCanvasView(board,bundle,prepared.choices,plan.actions,plan.actions);
assert.equal(plan.changed,0);assert.equal(view.useful.length,1);assert.equal(view.useful[0].a.id,"8");assert.equal(view.reviewGroups.length,2);
assert.equal(view.reviewGroups[0].items.length,2,"repeat attempt warnings grouped by assessment");
assert.equal(canvasAttemptTargets(board,"TEST1001",bundle.courses[0].assignments[0])[0].id,"quiz-6");
assert.equal(prepared.choices["101:8"],undefined,"placement suggestion is not an inferred calculation");
assert.equal(canvasAttemptTargets(board,"SOFT2412",bundle.courses[0].assignments[0]).length,0);
const duplicate=structuredClone(board);duplicate.tasks.push({...duplicate.tasks[2],id:"another-quiz-6"});
assert.equal(canvasAttemptTargets(duplicate,"TEST1001",bundle.courses[0].assignments[0]).length,2,"ambiguous quiz number is not a unique placement");
const status=canvasUpdateStatus(board,bundle,choices,plan.actions);
assert.equal(status.resultsToConnect.length,1);assert.equal(status.attention.length,3);
assert.equal(canvasResultsHeadline(0,1,view.reviewGroups.length),"1 Canvas result to review · 2 assessments need review");
assert.notEqual(canvasResultsHeadline(0,0,2),"No changes in last check");
const renamed=structuredClone(old);renamed.courses[0].groups[0].name="Display-only change";
assert.equal(planCanvasImport(board,renamed,choices).actions.filter(a=>a.kind==="attention").length,0);
const snapshot=JSON.parse(canvasSourceRules(old.courses[0],"5"));snapshot.group.rules.neverDrop=["1","2"];
const reordered=structuredClone(snapshot);reordered.group.rules.neverDrop=["2","1"];
assert.equal(canvasSourceRuleReview(JSON.stringify(snapshot),JSON.stringify(reordered)),null);
assert.equal(canvasSourceRuleReview("null",JSON.stringify(snapshot))?.canKeep,false);
const unknown=structuredClone(snapshot);unknown.group.rules.dropLowest=null;
assert.deepEqual(canvasSourceRuleReview(JSON.stringify(unknown),JSON.stringify(snapshot))?.changes,[{label:"Drop lowest",before:"Unknown",after:"0"}],"unknown is not a no-drop rule");
const firstGroup=view.reviewGroups[0];
assert.deepEqual(firstGroup.items[0].action?.sourceReview?.changes,[{label:"Drop lowest",before:"0",after:"1"}]);
const accept:CanvasChoice[]=choices.map(c=>({...c,...(c.targetId==="quiz-4"?{reviewedSourceRules:firstGroup.items[0].action!.sourceReview!.snapshot}:{})}));
const accepted=planCanvasImport(board,bundle,accept);
assert.equal(accepted.changed,2,"only the two reviewed source baselines will be saved");
assert.equal(accepted.actions.filter(a=>a.kind==="attention").length,1,"other quiz remains blocked");
assert.deepEqual(accepted.semester.tasks,board.tasks,"accepting source metadata does not change saved calculations or grades");
assert.equal(planCanvasImport(board,bundle,choices).changed,0,"cancel / Undo restores the original blocked preview");
assert.equal(planCanvasImport(board,bundle,accept.map(c=>({...c,reviewedSourceRules:"stale"}))).changed,0);
assert.equal(planCanvasImport(accepted.semester,bundle,choices).changed,0,"repeated accepted source is a no-op");
const changedAgain=structuredClone(bundle);changedAgain.courses[0].groups[0].weight=20;
assert.equal(planCanvasImport(board,changedAgain,accept).changed,0,"acknowledgement is bound to the exact source snapshot");
const maximumChanged=structuredClone(bundle);maximumChanged.courses[0].assignments.find(a=>a.id==="1")!.pointsPossible=50;
assert.equal(planCanvasImport(board,maximumChanged,accept).changed,1,"reviewing settings does not accept a changed source maximum");
const excused=structuredClone(bundle);excused.courses[0].assignments.find(a=>a.id==="1")!.submission!.excused=true;
assert.equal(planCanvasImport(board,excused,accept).changed,1,"reviewing settings does not override an excused source");
const unavailable=structuredClone(bundle);unavailable.courses[0].groupsUnavailable=true;
const missingPlan=planCanvasImport(board,unavailable,choices);
assert(missingPlan.actions.filter(a=>a.kind==="attention").every(a=>!a.sourceReview?.canKeep));
const manual=structuredClone(board);manual.tasks[0].gradePlan!.items[0].grade=null;
assert.equal(planCanvasImport(manual,bundle,accept).semester.tasks[0].gradePlan!.items[0].grade,null);
const stale=structuredClone(bundle);stale.courses[0].fetchedAt="2026-10-01T00:00:00Z";
assert.equal(planCanvasImport(board,stale,accept).changed,0);
assert.deepEqual(planCanvasImport(board,readCanvasBundle(raw),accept).semester,accepted.semester,"JSON and direct use identical review protection");
assert.deepEqual(readBackup(backupText(accepted.semester)).canvasImports,accepted.semester.canvasImports);
assert.equal(JSON.stringify(board),before);
const now=Date.parse(bundle.exportedAt)+1000;
assert.equal(canvasCheckFreshness(bundle,1,now).needsCheck,false);
assert.equal(canvasCheckFreshness(bundle,4,now).needsCheck,true,"partial read cannot mean all courses checked");
assert.equal(canvasCheckFreshness(bundle,1,now+60000).needsCheck,true);
assert.equal(canvasCheckFreshness(bundle,1,now-5000).needsCheck,true);
assert.equal(canvasCheckFreshness(null,4,now).needsCheck,true);
console.log("PASS attention flow: attempt placement not policy, grouped warnings, semantic changes, snapshot-bound review, cancel/Undo, manual/stale protection, repeat, JSON, backups and freshness.");
