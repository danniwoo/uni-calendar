import assert from "node:assert/strict";
import {fixtureBoard,fixtureBundle,fixtureChoices} from "./fixtures/canvas-connect";
import {planCanvasImport,suggestCanvasMatches,validCanvasMetadata} from "../lib/canvas-import";
import {confirmCanvasImport,markCanvasGradeSeen,unreadCanvasGrades,validCanvasHistory} from "../lib/canvas-history";
import {backupText,readBackup} from "../lib/backup";
import {mergeSemester} from "../lib/semester";
import {reconcile} from "../lib/sync";
const base=planCanvasImport(fixtureBoard,fixtureBundle,fixtureChoices).semester;
const fresh=structuredClone(fixtureBundle);
fresh.courses.forEach(c=>c.fetchedAt="2026-10-26T00:00:00Z");
fresh.courses[0].assignments[0].submission!.score=9;
base.tasks[2].grade=null;
const before=JSON.stringify(base),choices=Object.values(suggestCanvasMatches(base,fresh).choices);
assert.equal(planCanvasImport(base,fresh,choices).semester.canvasHistory,undefined,"Preview creates no receipt");
assert.equal(JSON.stringify(base),before,"Preview/cancel leave original board untouched");
const result=confirmCanvasImport(base,fresh,choices,"test-batch","2026-10-26T01:00:00Z"),s=result.semester;
assert.equal(s.canvasHistory?.length,1);assert.ok(validCanvasMetadata(s));
assert.equal(s.canvasHistory![0].entries.filter(e=>e.kind==="grade").length,1);
assert.match(s.canvasHistory![0].entries.find(e=>e.kind==="grade")!.text,/7\/10 → 9\/10/);
assert.equal(s.tasks[1].grade!.earned,8);assert.equal(s.tasks[2].grade,null);
assert.equal(unreadCanvasGrades(s).size,1);
assert.equal(confirmCanvasImport(s,fresh,choices,"repeat").semester.canvasHistory?.length,1,"Same-file no-op adds no history");
const target=s.canvasHistory![0].entries.find(e=>e.kind==="grade")!.targetId!;
const seen=markCanvasGradeSeen(s,target);assert.equal(unreadCanvasGrades(seen).size,0);assert.equal(unreadCanvasGrades(s).size,1);
assert.deepEqual(seen.tasks,s.tasks);assert.deepEqual(seen.canvasImports,s.canvasImports);assert.equal(seen.canvasHistory?.length,1);
assert.equal(markCanvasGradeSeen(seen,target),seen,"Repeated opens do not write");
assert.deepEqual(readBackup(backupText(seen)).canvasHistory,seen.canvasHistory);
assert.deepEqual(mergeSemester(seen,structuredClone(base)).canvasHistory,seen.canvasHistory);
const again=structuredClone(fresh);again.courses[0].assignments[0].submission!.score=10;
const updated=confirmCanvasImport(seen,again,choices,"next").semester;
assert.equal(unreadCanvasGrades(updated).size,1,"New source result re-arms indicator");
assert.equal(updated.canvasHistory?.length,2);
assert.equal(reconcile(s,seen,updated).conflicts.includes("canvasHistory"),true,"Conflicting history edits require a decision");
assert.equal(validCanvasHistory(s.canvasHistory,"123456"),false,"Account isolation");
assert.equal(validCanvasHistory([{...s.canvasHistory![0],entries:[{...s.canvasHistory![0].entries[0],kind:"unknown"}]}],s.canvasAccountId),false);
assert.throws(()=>readBackup(JSON.stringify({...s,canvasHistory:[{...s.canvasHistory![0],confirmedAt:"not-a-date"}]})),/invalid/);
assert.throws(()=>confirmCanvasImport(base,fresh,choices,"bad/id"),/record/);
let many=s;
for(let i=0;i<25;i++){const b=structuredClone(fresh);b.courses[0].assignments[0].submission!.score=i%2?8:9;many=confirmCanvasImport(many,b,choices,`history-${i}`).semester;}
assert.equal(many.canvasHistory?.length,20);assert.ok(validCanvasMetadata(many));
const ruleBoard=structuredClone(fixtureBoard);delete ruleBoard.tasks[0].grade;
const ruleChoice={...fixtureChoices[0],mode:"part" as const,rule:{method:"highest" as const,count:3}};
const rules=confirmCanvasImport(ruleBoard,fixtureBundle,[ruleChoice],"rule-import").semester;
assert.ok(validCanvasMetadata(rules));assert.equal(unreadCanvasGrades(rules).size,1);
assert.equal(rules.canvasHistory![0].entries.some(e=>e.key.startsWith("summary:")),false,"Calculated summaries are not duplicate source updates");
assert.equal(confirmCanvasImport(rules,fixtureBundle,[ruleChoice],"rule-repeat").semester.canvasHistory?.length,1);
console.log("Canvas history passed: confirmation-only receipts, repeat no-op, unread lifecycle, manual protection, backup/refresh, conflict, account and retention validation.");
