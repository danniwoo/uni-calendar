assert.throws(()=>updateAssessmentSteps(split,parent,[editRows[0],editRows[0]]),/list changed/);
assert.deepEqual(readBackup(backupText(replaced)).tasks,JSON.parse(JSON.stringify(replaced.tasks)));
assert.equal(mergeSemester(replaced,structuredClone(s)).tasks.find(t=>t.id===parts[1].id)?.date,"2026-10-19");
const movedClasses={...split,classes:s.classes.map(c=>({...c,time:"15:00",end:"17:00"}))};
const unchanged=updateAssessmentSteps(movedClasses,parent,parts.map(t=>assessmentStepFromTask(movedClasses,t)));
assert.equal(unchanged.tasks.find(t=>t.id===parts[0].id)?.time,"16:00","Unchanged steps must not silently follow a moved tutorial");
console.log("PASS: step editing retains IDs/progress/notes/scope, unique additions, removal/undo, backup, refresh and unchanged tutorial timing.");
