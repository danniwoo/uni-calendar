import assert from "node:assert/strict";
import {calendar,mergeSemester,type Semester,type Task} from "../lib/semester";
import {availabilityError,createAssessmentSteps,updateAssessmentSteps,assessmentStepFromTask,sprintSteps,stepTiming} from "../lib/assessment-schedule";
import {backupText,readBackup} from "../lib/backup";
import {weekData} from "../lib/week-calendar";
import {subjectAssessments} from "../lib/subject-view";
import {reconcile} from "../lib/sync";
const parent:Task={id:"project",kind:"assessment",unit:"TEST1001",title:"Project",weight:"10%",timing:"",description:"",source:"",sourceText:"",hurdle:false,group:true};
const s:Semester={year:2026,session:"S2C",weeks:calendar(2026,"S2C"),units:[{code:"TEST1001",name:"Test",session:"S2C",outline:"",summary:"",status:"ready",assessments:[parent],topics:[]}],tasks:[parent],classes:[10,11,12].map((week,i)=>({id:`tut${week}`,unit:"TEST1001",activity:"Tutorial",week,date:["2026-10-15","2026-10-22","2026-10-29"][i],time:"16:00",end:"18:00",location:"Room"})),completed:{},feedUrl:"",importedAt:"2026-10-14",warnings:[]};
const rows=sprintSteps(s,3,10),split=createAssessmentSteps(s,parent,rows),parts=split.tasks.filter(t=>t.parentId===parent.id);
assert.equal(parts.length,6);
assert.deepEqual(parts.filter(t=>t.timeBasis==="deadline").map(t=>[t.date,t.time]),[["2026-10-18","23:59"],["2026-10-25","23:59"],["2026-11-01","23:59"]]);
assert.deepEqual(parts.filter(t=>t.timeBasis==="class").map(t=>t.date),["2026-10-15","2026-10-22","2026-10-29"]);
assert.ok(parts.every(t=>t.weight==="" && !t.done));
assert.equal(split.tasks[0].weight,"10%");
assert.equal(subjectAssessments(split,"TEST1001").length,1);
assert.equal(weekData(split,"2026-10-12").linked.get("tut10")?.[0].id,parts[0].id);
assert.deepEqual(weekData(split,"2026-10-12").due.map(t=>t.id),[parts[1].id]);
const missing=stepTiming({...s,classes:[]},parent.unit,rows[0]);
assert.equal(missing.week,10);assert.equal(missing.date,undefined);
const ambiguous={...s,classes:[...s.classes,{...s.classes[0],id:"other",time:"12:00"}]};
assert.equal(stepTiming(ambiguous,parent.unit,rows[0]).date,undefined);
assert.equal(stepTiming(ambiguous,parent.unit,{...rows[0],classId:"other"}).time,"12:00");
assert.throws(()=>sprintSteps(s,3,12),/within/);
assert.throws(()=>createAssessmentSteps(split,parent,rows),/already/);
assert.throws(()=>createAssessmentSteps(s,parent,rows.map(r=>({...r,weight:"2"}))),/total/);
assert.throws(()=>createAssessmentSteps(s,parent,[{...rows[0],weight:"-1"},rows[1]]),/percentage/);
assert.equal(createAssessmentSteps(s,parent,[{...rows[0],weight:"4"},{...rows[1],weight:"6"}]).tasks.length,3);
assert.throws(()=>createAssessmentSteps(s,parent,[{...rows[1],date:"2026-02-30"},rows[0]]),/valid date/);
parts[0].done=true;
const refreshed=mergeSemester(split,structuredClone(s));
assert.equal(refreshed.tasks.find(t=>t.id===parts[0].id)?.done,true);
assert.equal(refreshed.tasks.find(t=>t.id===parts[1].id)?.done,false);
assert.equal(refreshed.tasks.find(t=>t.id===parent.id)?.splitCount,6);
const a4:Task={...parent,id:"a4",date:"2026-10-26",time:"23:59",availableFrom:"2026-10-13",availableUntil:"2026-11-02",availableUntilTime:"23:59",manual:true,overrides:["date","time","availableFrom","availableUntil","availableUntilTime"]};
assert.equal(availabilityError(a4),"");assert.equal(a4.availableFromTime,undefined);
for(const edit of [{availableFrom:"2026-11-03"},{availableUntil:"2026-10-25"},{availableFrom:"2026-02-30"},{availableFromTime:"24:00"},{availableFrom:undefined,availableFromTime:"10:00"},{availableUntil:"2026-10-26",availableUntilTime:"12:00"}])assert.ok(availabilityError({...a4,...edit}));
const dated={...split,tasks:[...split.tasks,a4]};
assert.deepEqual(readBackup(backupText(dated)).tasks,JSON.parse(JSON.stringify(dated.tasks)));
assert.throws(()=>readBackup(backupText({...dated,tasks:[{...a4,availableFrom:"2026-02-30"}]})),/invalid/);
const fresh={...s,tasks:[parent,{...parent,id:"a4"}]};
assert.equal(mergeSemester(dated,fresh).tasks.find(t=>t.id==="a4")?.availableUntil,"2026-11-02");
const local={...dated,tasks:dated.tasks.map(t=>t.id==="a4"?{...t,availableFrom:"2026-10-12"}:t)};
const remote={...dated,tasks:dated.tasks.map(t=>t.id===parts[1].id?{...t,done:true}:t)};
const merged=reconcile(dated,local,remote);assert.deepEqual(merged.conflicts,[]);
assert.equal(merged.semester.tasks.find(t=>t.id==="a4")?.availableFrom,"2026-10-12");
assert.equal(merged.semester.tasks.find(t=>t.id===parts[1].id)?.done,true);
console.log("PASS: sprint demos/submissions, unknown/unequal weights, class ambiguity, availability validation, backup, refresh and concurrent edits.");
parts[0].description="Keep my notes";parts[0].coverage=[1,2];parts[0].availableFrom="2026-10-01";
const editRows=parts.map(t=>assessmentStepFromTask(split,t));
editRows[1]={...editRows[1],date:"2026-10-19",time:"17:00"};
const updated=updateAssessmentSteps(split,parent,editRows);
assert.deepEqual(updated.tasks.find(t=>t.id===parts[0].id)?.coverage,[1,2]);
assert.equal(updated.tasks.find(t=>t.id===parts[0].id)?.description,"Keep my notes");
assert.equal(updated.tasks.find(t=>t.id===parts[0].id)?.availableFrom,"2026-10-01");
assert.equal(updated.tasks.find(t=>t.id===parts[0].id)?.done,true);
assert.equal(updated.tasks.find(t=>t.id===parts[1].id)?.date,"2026-10-19");
assert.equal(updated.tasks.find(t=>t.id===parts[1].id)?.week,11);
const replaceRows=[...editRows.slice(0,-1),{title:"Extra submission",mode:"week" as const,week:13}];
const replaced=updateAssessmentSteps(updated,parent,replaceRows);
assert.equal(replaced.tasks.some(t=>t.id===parts.at(-1)!.id),false);
assert.ok(replaced.tasks.find(t=>t.title==="Extra submission")?.id.includes("-step-"));
const undone=reconcile(replaced,updated,{...replaced,completed:{other:true}});
assert.deepEqual(undone.conflicts,[]);assert.deepEqual(undone.semester.completed,{other:true});
assert.ok(undone.semester.tasks.some(t=>t.id===parts.at(-1)!.id));
