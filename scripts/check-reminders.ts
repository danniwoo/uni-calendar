import assert from "node:assert/strict";
import {reminderError,reminderTime,reminderPreview,sydneyInstant,reminderJobs,type Reminder} from "../lib/reminders";
import {calendarFixture} from "./fixtures/calendar-visibility";
import {readBackup,backupText} from "../lib/backup";
import {mergeSemester} from "../lib/semester";
import {reconcile} from "../lib/sync";
import type {Task} from "../lib/semester";
const task={id:"synthetic-task",title:"Synthetic report",date:"2026-10-04",time:"12:00",done:false} as Task;
const day:Reminder={id:"a",kind:"day",days:1,time:"09:00"},offset:Reminder={id:"b",kind:"before",minutes:1440};
assert.equal(new Date(reminderTime(task,day)!).toISOString(),"2026-10-02T23:00:00.000Z");
assert.equal(new Date(reminderTime(task,offset)!).toISOString(),"2026-10-03T01:00:00.000Z");
assert.equal(reminderTime({...task,date:undefined},day),undefined);
assert.equal(reminderTime({...task,time:undefined},offset),undefined);
assert.equal(reminderTime({...task,allDay:true},offset),undefined);
assert.ok(reminderTime({...task,time:undefined},day));
assert.equal(sydneyInstant("2026-10-04","02:30"),undefined,"DST gap is not silently shifted");
assert.equal(sydneyInstant("2026-04-05","02:30"),undefined,"ambiguous DST time requires a different clock time");
assert.equal(sydneyInstant("2026-02-30","09:00"),undefined);
assert.equal(reminderError([day,offset]),undefined);
assert.ok(reminderError([day,{...day,id:"c"}]));
assert.ok(reminderError([day,{...offset,id:"a"}]));
assert.ok(reminderError([{...day,days:-1}]));
assert.ok(reminderError([{...day,time:"24:00"}]));
assert.ok(reminderError([{...offset,minutes:Infinity}]));
assert.ok(reminderError(new Array(6).fill(day)));
assert.match(reminderPreview({...task,done:true},day),/Paused/);
assert.match(reminderPreview(task,day,Date.parse("2026-11-01T00:00:00Z")),/past/);
assert.match(reminderPreview(task,day,0),/Sydney/);
assert.notEqual(reminderTime(task,day),reminderTime({...task,date:"2026-10-05"},day),"relative reminders follow a changed date");
const base=structuredClone(calendarFixture);base.tasks=[{...base.tasks[0],date:"2026-11-05",time:"12:00",reminders:[day,offset]}];
const serialized=JSON.stringify(base);
assert.equal(reminderJobs(base,0).length,2);
assert.equal(reminderJobs({...base,tasks:[{...base.tasks[0],done:true}]},0).length,0);
assert.equal(reminderJobs({...base,tasks:[]},0).length,0);
assert.equal(reminderJobs({...base,tasks:[{...base.tasks[0],date:undefined}]},0).length,0);
assert.equal(reminderJobs(base,Date.parse("2026-12-01")).length,0);
assert.equal(JSON.stringify(base),serialized,"planning never mutates a board");
assert.deepEqual(readBackup(backupText(base)).tasks[0].reminders,[day,offset]);
assert.throws(()=>readBackup(backupText({...base,tasks:[{...base.tasks[0],reminders:[{...day,days:-2}]}]})));
const fresh=structuredClone(base);delete fresh.tasks[0].reminders;
assert.deepEqual(mergeSemester(base,fresh).tasks[0].reminders,[day,offset],"timetable refresh preserves reminders");
const local=structuredClone(base),remote=structuredClone(base);local.tasks[0].reminders=[day];remote.tasks[0].reminders=[offset];
assert.ok(reconcile(base,local,remote).conflicts.some(c=>c.endsWith(".reminders")),"concurrent reminders require an explicit choice");
remote.tasks[0].reminders=base.tasks[0].reminders;remote.tasks[0].description="Unrelated notes";
assert.equal(reconcile(base,local,remote).conflicts.length,0);
console.log("Reminder timing, validation, completion/deletion, backup, refresh and conflict checks passed (synthetic data).");
