import assert from "node:assert/strict";
import {calendar,mergeSemester,type Semester,type Task} from "../lib/semester";
import {isPersonal,preparePersonal,eventClass} from "../lib/personal-items";
import {weekData,positionClasses} from "../lib/week-calendar";
import {monthEntries} from "../lib/month-calendar";
import {subjectTasks,subjectAssessments} from "../lib/subject-view";
import {backupText,readBackup,activeTasks} from "../lib/backup";
import {upgradeSemester} from "../lib/importer";
import {reconcile} from "../lib/sync";
const base:Task={id:"todo",kind:"task",unit:"",title:"Review notes",weight:"",timing:"",description:"",source:"",sourceText:"",manual:true,hurdle:false,group:false};
const s:Semester={year:2026,session:"S2C",weeks:calendar(2026,"S2C"),units:[{code:"TEST1001",name:"Test",session:"S2C",outline:"",summary:"",status:"ready",assessments:[],topics:[]}],tasks:[],classes:[],completed:{},feedUrl:"",importedAt:"2026-10-14",warnings:[]};
const todo=preparePersonal(base,s),dated=preparePersonal({...base,id:"dated",date:"2026-10-14",unit:"TEST1001"},s);
const event=preparePersonal({...base,id:"meeting",kind:"event",date:"2026-10-14",time:"21:00",endTime:"22:00",location:"Library",link:"https://example.com/meeting"},s);
const allDay=preparePersonal({...event,id:"all-day",allDay:true},s);
assert.equal(dated.time,undefined,"Date must not invent 23:59");
assert.equal(allDay.time,undefined);assert.equal(allDay.endTime,undefined);assert.equal(event.done,undefined);
for(const edit of [{title:" "},{unit:"MISSING"},{time:"12:00"},{date:"2026-02-30"},{kind:"event" as const},{...event,endTime:"20:00"},{...event,time:"25:00"},{...event,link:"javascript:alert(1)"}])assert.throws(()=>preparePersonal({...base,...edit},s));
const assessment={...dated,id:"quiz",kind:"quiz" as const};
const data={...s,tasks:[todo,dated,event,allDay,assessment]};
const week=weekData(data,"2026-10-12");
assert.deepEqual(week.events.map(t=>t.id),["meeting"]);
assert.deepEqual(week.unscheduled.map(t=>t.id),["todo"]);
assert.deepEqual(week.unknown,[]);
assert.deepEqual(week.due.map(t=>t.id),["dated","all-day","quiz"]);
assert.equal(weekData(data,"2026-10-12","TEST1001").events.length,0);
assert.equal(weekData(data,"2026-10-12","all",false).events.length,1,"Hiding classes must not hide meetings");
assert.equal(monthEntries(data).length,4);
assert.deepEqual(activeTasks(data).filter(t=>!isPersonal(t)).map(t=>t.id),["quiz"]);
assert.deepEqual(subjectTasks(data,"TEST1001","2026-10-14").upcoming.map(t=>t.id),["quiz"]);
assert.deepEqual(subjectAssessments(data,"TEST1001").map(t=>t.id),["quiz"]);
const layout=positionClasses([eventClass(event),{...eventClass(event),id:"overlap",time:"21:30",end:"22:30"}]);
assert.deepEqual(layout.map(p=>p.lanes),[2,2]);
assert.deepEqual(readBackup(backupText(data)).tasks,JSON.parse(JSON.stringify(data.tasks)));
assert.deepEqual(upgradeSemester(data).tasks,data.tasks);
assert.deepEqual(mergeSemester(data,structuredClone(s)).tasks,data.tasks);
const edited={...data,tasks:data.tasks.map(t=>t.id===event.id?{...t,title:"Updated meeting"}:t)};
const remote={...data,tasks:data.tasks.map(t=>t.id===dated.id?{...t,done:true}:t)};
const merged=reconcile(data,edited,remote);
assert.deepEqual(merged.conflicts,[]);assert.equal(merged.semester.tasks.find(t=>t.id===dated.id)?.done,true);
assert.equal(merged.semester.tasks.find(t=>t.id===event.id)?.title,"Updated meeting");
assert.equal(reconcile(data,{...data,tasks:data.tasks.filter(t=>t.id!==event.id)},data).semester.tasks.some(t=>t.id===event.id),false);
console.log("Personal tasks/events: validation, calendar placement, scope isolation, overlap, backup, refresh and concurrent edits pass.");
