import assert from "node:assert/strict";
import {onboardingBoard,onboardingBundle} from "./fixtures/canvas-onboarding";
import {prepareCanvasImport,preparedCandidates} from "../lib/canvas-prepare";
import {planCanvasImport,readCanvasBundle,canvasKey} from "../lib/canvas-import";
import {confirmCanvasImport} from "../lib/canvas-history";
import {defaultCanvasStage} from "../lib/canvas-update-status";
import {fixtureTasks} from "./fixtures/canvas-connect";
import {backupText,readBackup} from "../lib/backup";
import {mergeSemester} from "../lib/semester";
const s=structuredClone(onboardingBoard),b=structuredClone(onboardingBundle),before=JSON.stringify(s);
const prepared=prepareCanvasImport(s,b);
assert.equal(defaultCanvasStage(s,b),"prepared");
assert.equal(Object.keys(prepared.choices).length,4,"60 ungraded rows do not become onboarding chores");
assert(Object.values(prepared.choices).every(c=>c.targetId==="new"));
const plan=planCanvasImport(s,b,Object.values(prepared.choices));
assert.equal(JSON.stringify(s),before,"preparing and previewing cannot write");
assert.equal(plan.changed,4);assert.equal(plan.semester.tasks.length,4);
assert(plan.semester.tasks.every(t=>t.grade&&t.weight===""),"no group-weight or points-possible inference");
const saved=confirmCanvasImport(s,b,Object.values(prepared.choices),"test-import").semester;
assert.equal(saved.canvasHistory?.length,1);
const restored=readBackup(backupText(saved));
const repeat=prepareCanvasImport(restored,b);
assert(Object.values(repeat.choices).every(c=>c.targetId!=="new"),"source IDs reused after backup/reload");
assert.equal(planCanvasImport(restored,b,Object.values(repeat.choices)).changed,0);
const newer=structuredClone(b);newer.courses[0].fetchedAt="2026-10-26T00:00:00Z";newer.courses[0].assignments[0].submission!.score=18;
const updated=planCanvasImport(saved,newer,Object.values(prepareCanvasImport(saved,newer).choices));
assert.equal(updated.changed,1);assert.equal(updated.semester.tasks.length,4);
assert.deepEqual(prepareCanvasImport(s,readCanvasBundle(JSON.stringify(b))),prepared,"JSON / direct parity");

// Fresh account with no outline units also receives usable raw results.
const empty={...s,units:[]};
const newUnits=planCanvasImport(empty,b,Object.values(prepareCanvasImport(empty,b).choices)).semester;
assert.equal(newUnits.units.length,4);assert.equal(newUnits.tasks.length,4);
assert.equal(readBackup(backupText(newUnits)).units.length,4);
assert.equal(mergeSemester(newUnits,structuredClone(empty)).units.length,4,"timetable refresh retains Canvas-only course results");
assert.equal(mergeSemester(newUnits,{...structuredClone(empty),feedUrl:"different"}).units.length,0,"different board still isolated");
const wrongTerm=structuredClone(b);wrongTerm.courses[0].course.term="Semester 1 2025";
assert.equal(prepareCanvasImport(empty,wrongTerm).choices["101:1"],undefined);
const shared=structuredClone(b);shared.courses[0].course.code="ISYS2120 ISYS5120";
assert.equal(prepareCanvasImport(empty,shared).choices["101:1"],undefined,"ambiguous course code not guessed");

// Guessing identity uses independent evidence, never numerical marks as weight.
const target={...fixtureTasks[0],kind:"assessment" as const,title:"Conceptual Model Assignment",weight:"10%",date:"2026-10-25"};
const source={...b.courses[0].assignments[0],name:"Assignment 1 (10%)"};
const existing={...s,tasks:[target]};
assert.equal(preparedCandidates(existing,target.unit,source)[0].target.id,target.id);
assert.match(preparedCandidates(existing,target.unit,source)[0].reason,/Same due date/);
assert.equal(preparedCandidates(existing,target.unit,{...source,name:"Assignment 1",dueAt:null,pointsPossible:10}).length,0,"10 marks is not 10 percent");
assert.match(preparedCandidates(existing,target.unit,{...source,name:"Assignment 1"})[0].reason,/Both assignments.*Same due date/,"generic numbered assignment can use type + date as a tentative suggestion");
assert.equal(preparedCandidates(existing,target.unit,{...source,dueAt:null}).length,0,"weight alone not evidence");
const named={...existing,tasks:[{...target,title:"A1: Conceptual Model Assignment",date:"2026-10-31"}]};
assert.equal(preparedCandidates(named,target.unit,{...source,name:"Assignment 1"})[0].target.id,target.id,"personal due-date extension doesn't defeat assignment label");
const renamed=structuredClone(b);renamed.courses[0].assignments[0]=source;
const guessed=prepareCanvasImport(existing,renamed);
assert.equal(guessed.choices["101:1"].targetId,target.id);assert.match(guessed.reasons["101:1"],/^Suggested/);
const imported=planCanvasImport(existing,renamed,Object.values(guessed.choices));
assert.equal(imported.semester.tasks[0].date,target.date);assert.equal(imported.semester.tasks[0].weight,"10%");
const competing={...existing,tasks:[target,{...target,id:"other",title:"Logical Model Assignment"}]};
assert.equal(prepareCanvasImport(competing,renamed).choices["101:1"],undefined,"equal candidates require a choice, not silent selection");
const duplicateSource=structuredClone(renamed);duplicateSource.courses[0].assignments[1]={...source,id:"2"};
const duplicateDraft=prepareCanvasImport(existing,duplicateSource);
assert.equal(duplicateDraft.choices["101:1"],undefined);assert.equal(duplicateDraft.choices["101:2"],undefined);
assert.doesNotThrow(()=>planCanvasImport(existing,duplicateSource,Object.values(duplicateDraft.choices)),"one ambiguity cannot block good courses");
assert.equal(preparedCandidates({...existing,tasks:[{...target,title:"Final project presentation"}]},target.unit,{...source,name:"Final project report"}).length,0,"report versus presentation isn't the same result");
assert.equal(preparedCandidates(named,"SOFT2412",source).length,0,"unit boundary");
const protectedBoard={...existing,tasks:[{...target,grade:{earned:6,possible:20}}]};
const protectedPlan=planCanvasImport(protectedBoard,renamed,Object.values(prepareCanvasImport(protectedBoard,renamed).choices));
assert.deepEqual(protectedPlan.semester.tasks[0].grade,{earned:6,possible:20});assert(protectedPlan.actions.some(a=>a.kind==="protected"));
const clearBoard={...existing,tasks:[{...target,grade:null}]};
assert.equal(planCanvasImport(clearBoard,renamed,Object.values(prepareCanvasImport(clearBoard,renamed).choices)).semester.tasks[0].grade,null);
const badDate=structuredClone(b);badDate.courses[0].assignments[0].dueAt="2027-10-20T00:00:00Z";
assert.equal(Object.keys(prepareCanvasImport(s,badDate).choices).length,3,"bad date isolates one result");
const retake=structuredClone(b);retake.courses[0].assignments[0].name="Quiz 1 retake";
assert.equal(prepareCanvasImport(s,retake).choices["101:1"],undefined);
const weekly={...existing,tasks:[{...target,kind:"recurring" as const,title:"Weekly project activities"}]};
const weekSource=structuredClone(b);weekSource.courses[0].assignments[0].name="Weekly project activities";
assert.equal(prepareCanvasImport(weekly,weekSource).choices["101:1"],undefined,"exact recurring title is not an overall grade policy");
const deleted={...saved,tasks:saved.tasks.slice(1)};
assert.equal(prepareCanvasImport(deleted,b).choices["101:1"],undefined,"deleted imported task not recreated");
assert.equal(Object.keys(prepareCanvasImport(saved,{...b,accountId:"999"}).choices).length,0);
assert.throws(()=>planCanvasImport(saved,{...b,accountId:"999"},[]),/different Canvas account/);
assert.equal(saved.canvasImports?.[0].key,canvasKey(b,"101","1"));
// A first-time account with dozens of real marks gets a prepared batch, not
// a requirement to select every destination. All fixture values are invented.
const many=structuredClone(b),manyBoard=structuredClone(s);
many.courses.forEach((c,ci)=>c.assignments.forEach((a,i)=>{
  a.name=`Assignment ${i+1}`;a.pointsPossible=20;a.submission={released:true,excused:false,score:11,releaseEvidence:"marks-page",currentAttemptGraded:true};
  manyBoard.tasks.push({...fixtureTasks[ci],id:`many-${ci}-${i}`,kind:"assessment",title:`A${i+1}: Course assessment`,grade:undefined});
}));
const manyDraft=prepareCanvasImport(manyBoard,many);
assert.equal(Object.keys(manyDraft.choices).length,64);
assert(Object.values(manyDraft.choices).every(c=>c.targetId!=="new"));
assert.equal(planCanvasImport(manyBoard,many,Object.values(manyDraft.choices)).actions.filter(a=>a.kind==="grade").length,64);
assert.equal(planCanvasImport(s,many,Object.values(prepareCanvasImport(s,many).choices)).semester.tasks.length,64);
console.log("PASS: first-use 64 items → 4 prepared grades, new units, one commit, stable IDs, reload/update, candidate evidence/ambiguity, manual protection, no policy guesses, JSON parity.");
