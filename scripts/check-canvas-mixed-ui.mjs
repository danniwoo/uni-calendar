import assert from "node:assert/strict";
import {createRequire} from "node:module";
import {mixedUpdatesFixture} from "./fixtures/canvas-mixed-updates.ts";
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.SEMESTER_PLAYWRIGHT_PACKAGE||"playwright");
const browser=await chromium.launch({headless:true,...(process.env.SEMESTER_BROWSER_CHANNEL?{channel:process.env.SEMESTER_BROWSER_CHANNEL}:{})});
const page=await browser.newPage({viewport:{width:1280,height:1100}});
const errors=[];page.on("pageerror",e=>errors.push(e.message));
await page.route("**/*",r=>new URL(r.request().url()).hostname==="127.0.0.1"?r.continue():r.abort());
const shown=async locator=>locator.waitFor({state:"visible"});
const row=name=>page.getByRole("article",{name:`Prepared ${name}`,exact:true});
try{
  await page.goto("http://127.0.0.1:5184/?mixed");
  await shown(page.getByRole("heading",{name:"2 updates ready to import"}));
  await shown(page.getByRole("button",{name:"Import 2 updates",exact:true}));
  await shown(page.getByText("2 result updates",{exact:true}));
  await shown(row("Data modelling assignment"));
  await shown(row("Preparation 1").getByText("Complete · text only",{exact:true}));
  await shown(row("Preparation 1").getByText(/No recorded result → Complete → 0.5/));
  assert.equal(await row("Preparation 2").count(),0,"unchanged Complete is not a new update");
  await shown(row("Preparation 3").getByText("No change to save",{exact:true}));
  await row("Preparation 1").getByRole("button",{name:"Skip this check",exact:true}).click();
  await shown(page.getByRole("button",{name:"Import 1 update",exact:true}));
  await shown(row("Preparation 1").getByText("Skipped · no change",{exact:true}));
  await page.getByRole("button",{name:"Undo last change",exact:true}).click();
  await shown(page.getByRole("button",{name:"Import 2 updates",exact:true}));
  await page.getByRole("button",{name:"ELEC2302",exact:true}).click();
  assert.equal(await row("Data modelling assignment").count(),0);
  await shown(page.getByText("2 updates across all courses · nothing saved yet",{exact:true}));
  await shown(page.getByRole("button",{name:"Import 2 updates",exact:true}));
  await page.getByRole("button",{name:"All courses",exact:true}).click();
  await page.getByText("Calculated totals after import",{exact:true}).click();
  await shown(page.getByText(/These totals include saved results/));
  await page.screenshot({path:"/private/tmp/semester-mixed-updates.png",fullPage:true});
  await page.getByRole("button",{name:"Cancel",exact:true}).click();
  await shown(page.getByText("No live account. Test writes: 0",{exact:true}));
  await page.getByRole("button",{name:"Use JSON",exact:true}).click();
  await page.getByRole("button",{name:"Reopen preview",exact:true}).click();
  await page.getByLabel("Choose Connect import file").setInputFiles({name:"synthetic-mixed.json",mimeType:"application/json",buffer:Buffer.from(mixedUpdatesFixture().raw)});
  await shown(page.getByRole("heading",{name:"2 updates ready to import"}));
  await page.getByRole("button",{name:"Import 2 updates",exact:true}).click();
  await shown(page.getByText("No live account. Test writes: 1",{exact:true}));
  await page.getByRole("button",{name:"Reopen preview",exact:true}).click();
  await page.getByLabel("Choose Connect import file").setInputFiles({name:"synthetic-mixed.json",mimeType:"application/json",buffer:Buffer.from(mixedUpdatesFixture().raw)});
  await shown(page.getByRole("heading",{name:"You’re up to date"}));
  assert(await page.getByRole("button",{name:"Nothing to import",exact:true}).isDisabled());
  assert.deepEqual(errors,[]);
  console.log("PASS mixed UI: numeric + Complete listed, exact global import count, unchanged/protected no-ops excluded, Complete skip/Undo, total explanation, JSON parity, cancel zero writes, explicit in-memory import and repeat no-op.");
}finally{await browser.close();}
