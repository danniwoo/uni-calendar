import assert from "node:assert/strict";
import {classTimingPatch,deadlineTimingPatch,taskClassChoices,taskTimingKeys,timingEdited} from "../lib/task-timing";
import {calendarFixture} from "./fixtures/calendar-visibility";
import {mergeSemester,type Task} from "../lib/semester";
import {weekData} from "../lib/week-calendar";
import {backupText,readBackup} from "../lib/backup";
import {reminderJobs,sydneyInstant} from "../lib/reminders";
import {reconcile} from "../lib/sync";
const s=structuredClone(calendarFixture);
const original:Task={...s.tasks[0],date:"2026-11-01",week:12,time:"23:59",timeBasis:"deadline",grade:{earned:6,possible:8},description:"Manual note",reminders:[{id:"test-alert",kind:"before",minutes:30}]};
const c={...s.classes[0],id:"w13-tut",week:13,date:"2026-11-03",time:"12:00",end:"14:00"};
s.classes=[c,{...c,id:"w13-lec",activity:"Lecture",date:"2026-11-04",time:"09:00",end:"10:00"},{...c,id:"other-unit",unit:"TEST2002"}];s.tasks=[original];
const before=structuredClone(s);
const patch=classTimingPatch(s,original.unit,13,"Tutorial");
const edited:Task={...original,...patch,manual:true,overrides:[...taskTimingKeys]};
assert.equal(edited.date,"2026-11-03");assert.equal(edited.time,"12:00");assert.equal(edited.endTime,"14:00");assert.equal(edited.timeBasis,"class");assert.equal(edited.dueWeek,undefined);
assert.deepEqual(s,before);assert.deepEqual(edited.grade,original.grade);assert.equal(edited.description,original.description);
assert.ok(timingEdited(original,edited));assert.equal(timingEdited(edited,{...edited,title:"New title"}),false);
const saved={...s,tasks:[edited]};
assert.equal(weekData(saved,"2026-11-02").linked.get(c.id)?.[0].id,edited.id);
assert.equal(reminderJobs(saved,0)[0].when,sydneyInstant("2026-11-03","11:30"));
assert.deepEqual(readBackup(backupText(saved)).tasks,JSON.parse(JSON.stringify(saved.tasks)));
const refreshed=mergeSemester(saved,{...s,classes:s.classes.map(c=>({...c,time:"15:00",end:"17:00"}))});
assert.equal(refreshed.tasks[0].time,"12:00","A timetable refresh must not silently move a saved manual appointment");
assert.equal(classTimingPatch(s,original.unit,13,"Lecture").time,"09:00");
assert.equal(classTimingPatch(s,original.unit,13,"Lab").date,undefined);
assert.equal(classTimingPatch(s,original.unit,undefined,"Tutorial").date,undefined);
assert.equal(classTimingPatch(s,original.unit,13,"").week,13);
const multi={...s,classes:[...s.classes,{...c,id:"second",time:"16:00",end:"18:00"}]};
assert.equal(taskClassChoices(multi,original.unit,13,"Tutorial").length,2);
assert.equal(classTimingPatch(multi,original.unit,13,"Tutorial").date,undefined);
assert.equal(classTimingPatch(multi,original.unit,13,"Tutorial","second").time,"16:00");
assert.throws(()=>classTimingPatch(multi,original.unit,13,"Tutorial","other-unit"),/no longer/);
assert.throws(()=>classTimingPatch(s,original.unit,14,"Tutorial"),/teaching week/);
assert.throws(()=>classTimingPatch({...s,classes:[{...c,end:"11:00"}]},original.unit,13,"Tutorial"),/date and time/);
const date={...edited,...deadlineTimingPatch(edited)};
assert.equal(date.timeBasis,"deadline");assert.equal(date.endTime,undefined);assert.equal(date.date,edited.date);
const missing={...original,...classTimingPatch(s,original.unit,12,"Tutorial")};
assert.equal(missing.date,undefined);assert.equal(missing.time,undefined);assert.equal(reminderJobs({...s,tasks:[missing]},0).length,0);
// Simultaneous date and mode changes must not create a hybrid schedule.
const local={...s,tasks:[edited]},remote={...s,tasks:[{...original,time:"17:00"}]};
const conflict=reconcile(s,local,remote);assert.ok(conflict.conflicts.length);
assert.equal(conflict.semester.tasks[0].time,"12:00");
assert.equal(reconcile(s,local,remote,"remote").semester.tasks[0].timeBasis,"deadline");
const noteOnly={...s,tasks:[{...original,description:"Separate note edit"}]};
const combined=reconcile(s,local,noteOnly);
assert.equal(combined.conflicts.length,0);
assert.equal(combined.semester.tasks[0].timeBasis,"class");
assert.equal(combined.semester.tasks[0].description,"Separate note edit");
assert.deepEqual(readBackup(backupText(combined.semester)).tasks[0].reminders,original.reminders);
const cleared={...edited,...classTimingPatch(s,original.unit,13,"Lab")};
assert.equal(reconcile(saved,{...saved,tasks:[cleared]},{...saved,tasks:[{...edited,description:"Another note"}]}).semester.tasks[0].date,undefined);
const child={...original,parentId:"synthetic-parent",...patch};
assert.equal(child.timeBasis,"class");assert.equal(child.parentId,"synthetic-parent");
assert.equal(taskClassChoices(s,original.unit,13,"Lab").length,0);
console.log("PASS: week/class resolution, no guessing, grades/notes, reminder reschedule, backup/refresh and schedule conflict protection");
