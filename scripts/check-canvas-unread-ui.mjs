import assert from "node:assert/strict";
import {createRequire} from "node:module";
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.SEMESTER_PLAYWRIGHT_PACKAGE||"playwright");
const browser=await chromium.launch({headless:true,channel:process.env.SEMESTER_BROWSER_CHANNEL||"chrome"});
const page=await browser.newPage({viewport:{width:1280,height:1000}}),errors=[],api=[];
page.on("pageerror",e=>errors.push(e.message));
page.on("request",r=>{if(new URL(r.url()).pathname.startsWith("/api/"))api.push(r.url());});
await page.route("**/*",r=>new URL(r.request().url()).hostname==="127.0.0.1"?r.continue():r.abort());
const visible=async l=>l.waitFor({state:"visible"});
const badge=title=>page.getByRole("button",{name:`Mark Canvas update for ${title} as read`,exact:true});
const showGrades=async()=>{await page.getByRole("checkbox",{name:"Show grades",exact:true}).check();};
const writes=()=>page.evaluate(()=>Number(sessionStorage.getItem("qa-history-writes")||0));
const rearm=()=>page.evaluate(()=>{const s=JSON.parse(sessionStorage.getItem("qa-history-board"));s.canvasHistory.unshift({...structuredClone(s.canvasHistory[0]),id:`new-${s.canvasHistory.length}`,entries:s.canvasHistory[0].entries.map(e=>({...e,seen:false}))});sessionStorage.setItem("qa-history-board",JSON.stringify(s));});
try{
  await page.addInitScript(()=>localStorage.setItem("semester-view","assessments"));
  await page.goto("http://127.0.0.1:5184/?history");await showGrades();
  await visible(badge("Weekly quizzes"));await visible(badge("Project"));
  assert.equal(await writes(),0,"listing results is not an acknowledgement");
  await page.locator(".grade-table").getByRole("button",{name:"Weekly quizzes",exact:true}).click();
  await visible(page.getByRole("dialog"));
  await page.keyboard.press("Escape");
  await badge("Weekly quizzes").waitFor({state:"detached"});await visible(badge("Project"));
  assert.equal(await writes(),1,"opening assessment marks only its result read");
  await page.reload();await showGrades();
  assert.equal(await badge("Weekly quizzes").count(),0,"read state survives reload");
  await badge("Project").click();await badge("Project").waitFor({state:"detached"});
  assert.equal(await writes(),2);
  await page.locator(".grade-table").getByRole("button",{name:"Weekly quizzes",exact:true}).click();await page.keyboard.press("Escape");
  assert.equal(await writes(),2,"reopening an already-read assessment is a no-op");
  await rearm();await page.reload();await showGrades();await visible(badge("Weekly quizzes"));
  await page.getByRole("button",{name:"Edit grade for Weekly quizzes",exact:true}).click();
  await page.getByRole("button",{name:"Cancel",exact:true}).click();
  assert.equal(await badge("Weekly quizzes").count(),0,"canceling grade edits does not undo having read it");
  await page.locator(".grade-table tr").filter({has:badge("Project")}).getByRole("button",{name:"Individual grades for Project",exact:true}).click();
  await badge("Project").waitFor({state:"detached"});
  await page.getByRole("button",{name:"Cancel",exact:true}).click();
  await rearm();await page.reload();
  await page.getByRole("button",{name:/2 assessments have unseen Canvas/}).click();
  await page.getByRole("button",{name:/View ISYS2120 · Weekly quizzes grade/}).first().click();
  await visible(page.getByRole("form",{name:"Grade for Weekly quizzes"}));
  assert.equal(await badge("Weekly quizzes").count(),0,"history deep link acknowledges displayed grade");
  await page.getByRole("button",{name:"Cancel",exact:true}).click();
  await page.screenshot({path:"/private/tmp/semester-unread-qa.png",fullPage:true});
  assert.deepEqual(errors,[]);assert.deepEqual(api,[],"no account API traffic");
  console.log("PASS unread: title, badge, grade/parts editors and history link; cancel retains read state; reload and rearmed updates; repeated-open no-op; only read metadata changed, zero real API calls.");
}finally{await browser.close();}
