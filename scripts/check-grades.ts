import assert from "node:assert/strict";
import { calendar, mergeSemester, type Semester, type Task } from "../lib/semester";
import { gradeWeight, unitGrades, gradeTarget, saveGrade } from "../lib/grades";
import { validGrade } from "../lib/grade-value";
import { readBackup, backupText } from "../lib/backup";
import { reconcile } from "../lib/sync";
import { upgradeSemester } from "../lib/importer";
import { assessmentRows, defaultAssessmentFilters } from "../lib/assessment-list";

const base:Task={id:"quiz",unit:"TEST1001",title:"Quiz",kind:"quiz",weight:"10%",timing:"Due",description:"",source:"",sourceText:"",hurdle:false,group:false};
const tasks:Task[]=[{...base,grade:{earned:14,possible:20}},{...base,id:"report",title:"Report",weight:"20%",grade:{earned:16,possible:20}},
  {...base,id:"project",title:"Project",weight:"30%",splitCount:2},{...base,id:"exam",title:"Exam",weight:"40%",kind:"exam",hurdle:true},
  {...base,id:"part-1",weight:"15%",parentId:"project",grade:{earned:1,possible:1}},
  {...base,id:"part-2",weight:"15%",parentId:"project"},{...base,id:"meeting",kind:"event",weight:"10%",grade:{earned:1,possible:1}}];
const s:Semester={year:2026,session:"S2C",weeks:calendar(2026,"S2C"),feedUrl:"",importedAt:"",completed:{},classes:[],warnings:[],units:[{code:"TEST1001",name:"Test",session:"S2C",outline:"",status:"ready",summary:"",topics:[],assessments:tasks.slice(0,4)}],tasks};
const before=JSON.stringify(s);
let stats=unitGrades(s,"TEST1001");
assert.equal(stats.earned,23);assert.equal(stats.gradedWeight,30);assert.equal(stats.gradedCount,2);assert.equal(stats.complete,true);assert.equal(stats.remaining,70);
assert(Math.abs(stats.average!-76.6666666667)<1e-8);
const forecast=gradeTarget(stats,75);assert.equal(forecast.status,"needed");if(forecast.status==="needed")assert(Math.abs(forecast.average-74.2857142857)<1e-8);
assert.equal(unitGrades(s,"OTHER").average,null);
assert.equal(JSON.stringify(s),before,"Calculations do not mutate data");
const zero=saveGrade(s,"exam",{earned:0,possible:100},undefined);
assert.equal(unitGrades(zero,"TEST1001").gradedWeight,70,"Explicit zero counts as graded");
assert.equal(gradeTarget(unitGrades(zero,"TEST1001"),85).status,"unreachable");
assert.equal(zero.tasks.find(t=>t.id==="exam")?.done,undefined,"Entering a grade never completes a task");
const cleared=saveGrade(zero,"exam",null,{earned:0,possible:100});assert.equal(unitGrades(cleared,"TEST1001").gradedWeight,30);
assert.throws(()=>saveGrade(s,"quiz",{earned:15,possible:20},{earned:10,possible:20}),/changed elsewhere/);
for(const value of [{earned:-1,possible:20},{earned:21,possible:20},{earned:0,possible:0},{earned:NaN,possible:20},{earned:14,possible:Infinity},{earned:"14",possible:20}])assert.equal(validGrade(value),false);
for(const weight of ["","3% each","10–20%","10% bonus","110%","-5%","0.5% each · 4% cap"])assert.equal(gradeWeight({...base,weight}),null);
assert.equal(gradeWeight({...base,weight:"2.5% total"}),2.5);
assert.equal(gradeWeight({...base,rules:{text:"conflict",total:15}}),null);
assert.equal(gradeWeight({...base,weight:"0%"}),0);
const incomplete={...s,tasks:s.tasks.map(t=>t.id==="exam"?{...t,weight:""}:t)};
assert.equal(gradeTarget(unitGrades(incomplete,"TEST1001"),50).status,"incomplete");
assert.equal(unitGrades({...s,tasks:s.tasks.map(t=>t.id==="exam"?{...t,weight:"30%"}:t)},"TEST1001").complete,false);
const optional={...s,tasks:[...s.tasks,{...base,id:"bonus",rules:{text:"bonus",optional:true}}]};
assert.equal(unitGrades(optional,"TEST1001").complete,false);
const all=tasks.map(t=>({...t,grade:{earned:1,possible:1}}));
assert.equal(gradeTarget(unitGrades({...s,tasks:all},"TEST1001"),85).status,"reached");
assert.equal(gradeTarget(unitGrades({...s,tasks:all.map(t=>({...t,grade:{earned:0,possible:1}}))},"TEST1001"),50).status,"finished");
const recurring={...s,tasks:s.tasks.map(t=>t.id==="project"?{...t,kind:"recurring" as const,grade:{earned:70,possible:100},rules:{text:"best seven",total:30,bestOf:7}}:t)};
assert.equal(unitGrades(recurring,"TEST1001").earned,44,"Overall reported recurring grade is counted once");
assert.equal(assessmentRows(recurring,{...defaultAssessmentFilters,hideRecurring:true},"2026-10-18","overview").some(r=>r.task.id==="project"),false);
assert.equal(unitGrades(recurring,"TEST1001").earned,44,"Display filters do not affect unit statistics");
const importedOnly={...s,tasks:s.tasks.filter(t=>t.id!=="quiz")};
const saved=saveGrade(importedOnly,"quiz",{earned:15,possible:20},{earned:14,possible:20});
assert.equal(saved.tasks.filter(t=>t.id==="quiz").length,1);assert.equal(saved.tasks.at(-1)?.manual,undefined);
const fresh={...structuredClone(s),tasks:s.tasks.map(({grade,...t})=>t)};
assert.deepEqual(mergeSemester(saved,fresh).tasks.find(t=>t.id==="quiz")?.grade,{earned:15,possible:20});
assert.deepEqual(readBackup(backupText(saved)).tasks.find(t=>t.id==="quiz")?.grade,{earned:15,possible:20});
assert.deepEqual(upgradeSemester(saved).tasks.find(t=>t.id==="quiz")?.grade,{earned:15,possible:20});
assert.throws(()=>readBackup(JSON.stringify({...s,tasks:[{...base,grade:{earned:21,possible:20}}]})),/invalid/);
const local=saveGrade(s,"quiz",{earned:15,possible:20},{earned:14,possible:20});
const remote=saveGrade(s,"quiz",{earned:14,possible:25},{earned:14,possible:20});
const conflict=reconcile(s,local,remote);
assert(conflict.conflicts.includes("tasks.quiz.grade"));assert.deepEqual(conflict.semester.tasks[0].grade,{earned:15,possible:20},"Never merge earned and maximum from conflicting edits");
const independent={...structuredClone(s),tasks:s.tasks.map(t=>t.id==="quiz"?{...t,done:true}:t)};
const merged=reconcile(s,local,independent);assert.equal(merged.conflicts.length,0);assert.equal(merged.semester.tasks[0].done,true);assert.deepEqual(merged.semester.tasks[0].grade,{earned:15,possible:20});
console.log("PASS: grade math, zeros/blanks, aggregate isolation, targets, uncertain weights, recurring filters, persistence/import/backup and atomic cross-tab conflict handling.");
