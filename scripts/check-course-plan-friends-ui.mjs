// Disposable local QA only. The course-plan server uses synthetic Alice/Bob/Eve records.
import assert from "node:assert/strict";
import {createRequire} from "node:module";
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.SEMESTER_PLAYWRIGHT_PACKAGE||"playwright");
const browser=await chromium.launch({headless:true,...(process.env.SEMESTER_BROWSER_CHANNEL?{channel:process.env.SEMESTER_BROWSER_CHANNEL}:{})});
const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[];
page.on("pageerror",error=>errors.push(error.message));
try {
  await page.goto("http://127.0.0.1:5193/plan?view=friends");
  await page.getByRole("heading",{name:"Friends",exact:true}).waitFor();
  const setup=page.locator("#add-friend");
  await setup.getByRole("heading",{name:"Add a friend",exact:true}).waitFor();
  await setup.getByText("Use their invite",{exact:true}).waitFor();
  await setup.getByText("Share yours",{exact:true}).waitFor();
  await setup.getByLabel("Friend’s invitation",{exact:true}).waitFor();
  assert.equal(await setup.locator("details").count(),0,"friend code is not hidden in a disclosure");
  const create=setup.getByRole("button",{name:"Create my invite",exact:true});
  await create.click();
  await setup.getByText("Your invite is ready",{exact:true}).waitFor();
  assert.equal(await setup.getByLabel("Your invitation link",{exact:true}).count(),0,"long invitation URL stays behind the copy action");
  await setup.getByRole("button",{name:"Copy link",exact:true}).waitFor();
  await setup.getByRole("button",{name:"Copy code",exact:true}).waitFor();
  const code=await setup.locator(".course-code-row code").innerText();
  assert.match(code,/^(?:[A-F0-9]{4}-){7}[A-F0-9]{4}$/,"code is grouped for scanning and manual entry");
  if(process.env.SEMESTER_FRIENDS_SCREENSHOT)await page.screenshot({path:process.env.SEMESTER_FRIENDS_SCREENSHOT,fullPage:true});
  await page.reload();
  await setup.getByText("Your invite is ready",{exact:true}).waitFor();
  assert.equal(await setup.locator(".course-code-row code").innerText(),code,"same-browser reload restores only the matching active code");
  await page.context().addCookies([{name:"qa_actor",value:"bob",url:"http://127.0.0.1:5193"}]);
  await page.reload();
  await setup.getByRole("button",{name:"Create my invite",exact:true}).waitFor();
  assert.equal(await setup.getByText("Your invite is ready",{exact:true}).count(),0,"a different account never sees the cached code");
  await setup.getByLabel("Friend’s invitation",{exact:true}).fill(code);
  await setup.getByRole("button",{name:"Find friend",exact:true}).click();
  await setup.getByText("Sample alice",{exact:true}).waitFor();
  await setup.getByRole("button",{name:"Send request to Sample alice",exact:true}).click();
  await page.context().addCookies([{name:"qa_actor",value:"alice",url:"http://127.0.0.1:5193"}]);
  await page.reload();
  await setup.getByText("Your earlier invite is still active, but its code is not saved on this device.",{exact:true}).waitFor();
  await setup.getByRole("button",{name:"Create replacement code",exact:true}).waitFor();
  const request=page.locator(".course-connection").filter({hasText:"Sample bob"});
  await request.getByText("Wants to connect",{exact:true}).waitFor();
  await request.getByRole("button",{name:"Accept",exact:true}).click();
  await request.getByText("Friends",{exact:true}).waitFor();
  const mobile=await browser.newPage({viewport:{width:390,height:844}});
  await mobile.goto("http://127.0.0.1:5193/plan?view=friends");
  await mobile.locator("#add-friend").waitFor();
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,"friends page has no horizontal overflow at 390px");
  await mobile.close();
  assert.deepEqual(errors,[]);
  console.log("PASS UI: friend entry is always visible, link/code paths are explicit, code is directly copyable, request/accept works, active-invite recovery is clear, and 390px has no overflow.");
} finally {await browser.close();}
