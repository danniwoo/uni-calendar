import assert from "node:assert/strict";
import {canvasMatchSections,canvasMatchStatus,canvasTargetLabel,simpleCanvasDestination} from "../lib/canvas-match-view";
import {planCanvasImport,readCanvasBundle,suggestCanvasMatches} from "../lib/canvas-import";
import {fixtureBoard,fixtureBundle,fixtureChoices} from "./fixtures/canvas-connect";

const board=structuredClone(fixtureBoard),bundle=structuredClone(fixtureBundle);
const c=bundle.courses[3],root=board.tasks[3];
root.title="Design report";root.weight="6%";
board.tasks.push({...root,id:"talk",title:"Design presentation",weight:"4%"});
c.groups[0].name="Design portfolio";c.groups[0].weight=10;
c.assignments[0].name="Design report";c.assignments[1].name="Design presentation";
c.assignments.push({...structuredClone(c.assignments[1]),id:"3",name:"Peer feedback",pointsPossible:0});
const suggestions=suggestCanvasMatches(board,bundle);
const groups=canvasMatchSections(c,c.assignments,suggestions.choices,board.tasks);
assert.equal(groups.length,1);
assert.equal(groups[0].items.length,3,"auxiliary items are not silently dropped");
assert.equal(groups[0].destinations.length,2,"one group may link multiple independent assessments");
assert.deepEqual(groups[0].destinations.map(t=>t.weight),["6%","4%"]);
assert.equal(groups[0].weight,10,"Canvas group weight is display-only, not copied to child weights");
const jsonSuggestions=suggestCanvasMatches(board,readCanvasBundle(JSON.stringify(bundle)));
assert.deepEqual(jsonSuggestions,suggestions,"JSON and direct snapshots reuse identical matching");
const applied=planCanvasImport(board,bundle,Object.values(suggestions.choices));
assert.equal(applied.semester.tasks.find(t=>t.id==="talk")?.gradePlan,undefined);
assert.equal(applied.semester.tasks[3].weight,"6%");
const reused=suggestCanvasMatches(applied.semester,bundle);
assert.equal(planCanvasImport(applied.semester,bundle,Object.values(reused.choices)).changed,0);
assert.equal(canvasMatchStatus(undefined,undefined),"Not linked · optional");
const prior=applied.semester.canvasImports!.find(r=>r.targetId===root.id)!;
assert.equal(canvasMatchSections(c,c.assignments,{},board.tasks,applied.semester.canvasImports)[0].destinations.length,2,"skipping this check keeps saved destinations in the group map");
const choice=reused.choices["104:1"];
assert.equal(canvasMatchStatus(undefined,prior),"Linked · skipped this check");
assert.equal(canvasMatchStatus(choice,prior),"Linked · waiting for a result");
assert.equal(canvasMatchStatus(choice,prior,undefined,c.assignments[0]),"Linked · result unchanged");
assert.equal(canvasMatchStatus(choice,prior,{key:prior.key,changed:false,kind:"protected",text:"kept"}),"Manual data protected");
assert.equal(canvasMatchStatus(choice,prior,{key:prior.key,changed:true,kind:"grade",text:"updated"}),"Linked · new result");
assert.equal(canvasTargetLabel(root),"Design report · 6%");
assert.equal(simpleCanvasDestination({...root,kind:"assessment",series:undefined,gradePlan:undefined},[]),true,"only a chosen ordinary assessment gets the visible whole-grade default");
assert.equal(simpleCanvasDestination({...root,kind:"recurring"},[]),false);
assert.equal(simpleCanvasDestination(root,[{...root,id:"child",parentId:root.id}]),false,"existing child entries require an explicit placement decision");
assert.equal(simpleCanvasDestination({...root,gradePlan:{mode:"parts",method:"points",items:[]}},[]),false,"an existing grade plan is not defaulted to a whole result");
assert.equal(simpleCanvasDestination({...root,series:"weekly"},[]),false);
const orphan={...c.assignments[0],id:"99",groupId:"999"};
assert.equal(canvasMatchSections(c,[orphan],{},[])[0].name,"Other Canvas items");
const filtered=canvasMatchSections(c,[c.assignments[2]],{},board.tasks,applied.semester.canvasImports)[0];
assert.equal(filtered.destinations.length,2,"filtering unconnected items retains the group's existing destinations");
assert.equal(filtered.linked.length,2,"confirmed links remain available as context without duplicate editable rows");
const ungrouped={...orphan,groupId:null};
assert.equal(canvasMatchSections(c,[ungrouped],{},[])[0].items.length,1);
const unlinked=structuredClone(board);unlinked.tasks[3].title="Design scope report";
assert.equal(suggestCanvasMatches(unlinked,bundle).choices["104:1"],undefined,"similar title is not silently linked");
const skipped=planCanvasImport(applied.semester,bundle,[]);
assert.deepEqual(skipped.semester.canvasImports,applied.semester.canvasImports,"skip never deletes a confirmed link");
const future=structuredClone(bundle);
Object.assign(future.courses[3].assignments[1].submission!,{released:true,score:6,releaseEvidence:"marks-page"});
assert.equal(planCanvasImport(applied.semester,future,Object.values(reused.choices)).semester.tasks.find(t=>t.id==="talk")?.grade?.earned,6,"blank linked item gets future result without re-matching");
assert.equal(JSON.stringify(fixtureChoices).includes("Design"),false,"shared fixtures untouched");
console.log("PASS: group-to-independent-assessment map, explicit statuses, weights, orphan items, safe suggestions, JSON parity, saved links and future grades.");
